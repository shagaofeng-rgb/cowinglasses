export function quoteHref(locale: Locale, product?: string, color?: string) {
  const params = new URLSearchParams();
  if (product) params.set("product", product);
  if (color) params.set("color", color);
  return `/${locale}/quote${params.size ? `?${params}` : ""}`;
}
